import { SolverResult, Flashcard, QuizQuestion } from '../types';

export interface GeminiSolveParams {
  apiKey?: string;
  model?: string;
  questionText?: string;
  imageBase64?: string;
  imageMimeType?: string;
  subjectName: string;
  examBoard: string;
  gradeLevel: string;
}

export async function solveQuestionWithGemini(params: GeminiSolveParams): Promise<SolverResult> {
  const { apiKey, model = 'gemini-2.5-flash', questionText, imageBase64, imageMimeType, subjectName, examBoard, gradeLevel } = params;

  // If no API key provided, return simulated high-grade IGCSE examiner breakdown
  if (!apiKey || apiKey.trim() === '') {
    return generateSimulatedSolution(questionText || 'Uploaded Question Image', subjectName, examBoard, gradeLevel);
  }

  const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey.trim()}`;

  const prompt = `
You are a senior Chief Examiner for ${examBoard} IGCSE ${subjectName} (${gradeLevel}).
Analyze this student question thoroughly and return your answer STRICTLY as a valid JSON object matching this schema:
{
  "questionText": "A clean transcribed summary of the question",
  "subject": "${subjectName}",
  "topic": "Specific syllabus topic name",
  "totalMarks": 4,
  "stepByStepSolution": [
    {
      "stepNumber": 1,
      "title": "Method / Formula Step",
      "explanation": "Detailed explanation of what to write and why",
      "mathOrCode": "LaTeX formatted math equation or code snippet if applicable",
      "markAwarded": "[M1] Method Mark"
    }
  ],
  "finalAnswer": "Concise final answer with exact units and 3 significant figures",
  "markSchemeBreakdown": [
    "[M1] Description of mark 1",
    "[A1] Description of accuracy mark"
  ],
  "examinerTips": [
    "Secret examiner tip for this specific question style"
  ],
  "commonMistakes": [
    "Common student mistake from examiner reports"
  ],
  "relatedTopic": "Related syllabus sub-topic for further revision"
}

Ensure standard IGCSE marking criteria: [M] method, [A] accuracy, [B] independent mark, [SC] special case. Use LaTeX formatting ($...$ or $$...$$) for mathematical expressions and chemical formulas.
DO NOT wrap your output in markdown code blocks like \`\`\`json. Return only raw parseable JSON.
`;

  const contents: any[] = [];
  const parts: any[] = [];

  if (questionText) {
    parts.push({ text: `Question:\n${questionText}\n\nInstructions:\n${prompt}` });
  } else {
    parts.push({ text: `Instructions:\n${prompt}` });
  }

  if (imageBase64) {
    parts.push({
      inlineData: {
        mimeType: imageMimeType || 'image/jpeg',
        data: imageBase64.replace(/^data:image\/[a-z]+;base64,/, '')
      }
    });
  }

  contents.push({ parts });

  try {
    const res = await fetch(endpoint, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        contents,
        generationConfig: {
          temperature: 0.2,
          responseMimeType: "application/json"
        }
      })
    });

    if (!res.ok) {
      const errData = await res.json().catch(() => ({}));
      throw new Error(errData?.error?.message || `Gemini API error: ${res.statusText}`);
    }

    const data = await res.json();
    const candidate = data.candidates?.[0]?.content?.parts?.[0]?.text;
    if (!candidate) throw new Error('No response generated by Gemini model.');

    // Clean any accidental markdown backticks
    const cleanedJson = candidate.replace(/```json/g, '').replace(/```/g, '').trim();
    const parsed: SolverResult = JSON.parse(cleanedJson);
    return parsed;
  } catch (error: any) {
    console.warn('Live Gemini call failed, falling back to simulated solution:', error.message);
    const fallback = generateSimulatedSolution(questionText || 'Image question', subjectName, examBoard, gradeLevel);
    fallback.examinerTips.unshift(`Note: API response fell back due to: ${error.message}. Showing verified syllabus template.`);
    return fallback;
  }
}

export async function generateFlashcardsWithGemini(
  subjectName: string,
  topic: string,
  count: number = 4,
  apiKey?: string,
  model: string = 'gemini-2.5-flash'
): Promise<Flashcard[]> {
  if (!apiKey || apiKey.trim() === '') {
    return [
      {
        id: `gen-fc-${Date.now()}-1`,
        subjectId: subjectName,
        topic: topic,
        question: `What are the key syllabus definitions for ${topic}?`,
        answer: `In IGCSE, definitions must match the syllabus glossary verbatim to guarantee the 1-2 marks. Ensure you state units and conditions where relevant.`,
        examinerTip: `Check past paper mark schemes for keywords that are underlined (mandatory for marks).`,
        difficulty: 'Core',
        mastered: false,
      },
      {
        id: `gen-fc-${Date.now()}-2`,
        subjectId: subjectName,
        topic: topic,
        question: `What formula or law is most frequently tested under ${topic}?`,
        answer: `Identify the primary relationship between variables in this topic and practice rearranging it to make each variable the subject.`,
        examinerTip: `Always state the formula first before substituting numbers.`,
        difficulty: 'Extended',
        mastered: false,
      }
    ];
  }

  const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey.trim()}`;

  const prompt = `
Generate ${count} top-tier IGCSE flashcards for the subject "${subjectName}" on the topic "${topic}".
Output STRICTLY a JSON array of objects with the following schema:
[
  {
    "id": "fc-ai-1",
    "subjectId": "${subjectName}",
    "topic": "${topic}",
    "question": "Clear IGCSE question or prompt",
    "answer": "Accurate, mark-scheme aligned answer with LaTeX math if needed",
    "keyFormula": "Formula if applicable",
    "examinerTip": "Pro-tip from examiner reports",
    "difficulty": "Extended"
  }
]
`;

  try {
    const res = await fetch(endpoint, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        contents: [{ parts: [{ text: prompt }] }],
        generationConfig: { responseMimeType: "application/json" }
      })
    });
    const data = await res.json();
    const candidate = data.candidates?.[0]?.content?.parts?.[0]?.text;
    const cleaned = candidate.replace(/```json/g, '').replace(/```/g, '').trim();
    return JSON.parse(cleaned);
  } catch (err) {
    console.error('Error generating flashcards:', err);
    throw err;
  }
}

