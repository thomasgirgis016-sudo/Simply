export async function askAiTutor(
  messages: { role: 'user' | 'assistant' | 'system'; content: string }[],
  subjectName: string,
  examBoard: string,
  apiKey?: string,
  model: string = 'gemini-2.5-flash'
): Promise<string> {
  if (!apiKey || apiKey.trim() === '') {
    const lastUserMessage = messages[messages.length - 1]?.content.toLowerCase() || '';
    if (lastUserMessage.includes('grade') || lastUserMessage.includes('a*') || lastUserMessage.includes('9')) {
      return `To secure a Grade 9 / A* in ${examBoard} ${subjectName}:\n\n1. **Master the Command Words**: Examiners differentiate Grade 7 from Grade 9 students by whether they just *describe* or properly *explain* with causal links ("because", "leading to").\n2. **Look for [M] marks**: Even if your final number is wrong, writing the formula and working out gets you 70-80% of marks!\n3. **Use standard units & 3 significant figures**: In Cambridge IGCSE, leaving an answer unrounded or rounded to 1 s.f. costs an accuracy mark.`;
    }
    return `Hello! I am your AI IGCSE Co-Pilot for **${examBoard} ${subjectName}**.\n\nYou can ask me to:\n- Explain any difficult concept or past paper question\n- Review your answers against official IGCSE mark scheme keywords\n- Give you quick drill questions or mnemonics to remember tricky definitions.\n\n*(Tip: Add your Gemini API key in Settings to unlock unlimited live conversational tutoring!)*`;
  }

  const endpoint = `https://generativelanguage.googleapis.com/v1beta/models/${model}:generateContent?key=${apiKey.trim()}`;

  const systemInstruction = `You are "Simply IGCSE Co-Pilot", an elite Cambridge & Edexcel IGCSE examiner and private tutor.
The student is studying: ${examBoard} ${subjectName}.
Tone: Encouraging, rigorous, mark-scheme focused. Always point out where [M] method marks, [A] accuracy marks, and [B] independent marks are awarded.
Use LaTeX ($...$ or $$...$$) for any mathematical equations or chemical reactions.`;

  const formattedContents = messages.map(m => ({
    role: m.role === 'assistant' ? 'model' : 'user',
    parts: [{ text: m.content }]
  }));

  try {
    const res = await fetch(endpoint, {
      method: 'POST',
      headers: { 'Content-Type': 'application/json' },
      body: JSON.stringify({
        systemInstruction: { parts: [{ text: systemInstruction }] },
        contents: formattedContents,
        generationConfig: {
          temperature: 0.6,
          maxOutputTokens: 1000
        }
      })
    });

    if (!res.ok) {
      throw new Error(`API error: ${res.statusText}`);
    }

    const data = await res.json();
    return data.candidates?.[0]?.content?.parts?.[0]?.text || 'No response generated.';
  } catch (err: any) {
    return `I encountered an issue connecting to Gemini: ${err.message}. Please verify your API key in Settings.`;
  }
}

